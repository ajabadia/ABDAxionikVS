#!/usr/bin/env node
/**
 * ABDAxionikVS — build_webui.js
 * Genera BuildVersion y compila el bundle WebUI con Vite en WebUI/dist/
 */

import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const now = new Date();
const pad = (n) => String(n).padStart(2, '0');
const buildNum = `${now.getFullYear()}.${pad(now.getMonth() + 1)}.${pad(now.getDate())}.${pad(now.getHours())}${pad(now.getMinutes())}`;
const buildTime = now.toISOString();

console.log(`[ABDAxionikVS] Build Version: ${buildNum} (${buildTime})`);

// 1. Source/Generated/BuildVersion.gen.h
const buildHeaderPath = path.join(rootDir, 'Source', 'Generated', 'BuildVersion.gen.h');
fs.mkdirSync(path.dirname(buildHeaderPath), { recursive: true });

const buildHeaderContent = `// AUTO-GENERATED BY Scripts/build_webui.js - DO NOT EDIT MANUALLY
#pragma once

namespace abd::axionik {
    inline constexpr const char* kVersionString = "1.0.0";
    inline constexpr const char* kBuildNumber = "${buildNum}";
    inline constexpr const char* kBuildTimestamp = "${buildTime}";
    inline constexpr const char* kProductName = "ABDAxionikVS";
    inline constexpr const char* kManufacturer = "ABDSynths";
}
`;

fs.writeFileSync(buildHeaderPath, buildHeaderContent, 'utf8');

// 2. WebUI/src/generated/buildVersion.ts
const buildTsPath = path.join(rootDir, 'WebUI', 'src', 'generated', 'buildVersion.ts');
fs.mkdirSync(path.dirname(buildTsPath), { recursive: true });

const buildTsContent = `// AUTO-GENERATED BY Scripts/build_webui.js - DO NOT EDIT MANUALLY
export const BUILD_INFO = {
  version: "1.0.0",
  buildNumber: "${buildNum}",
  buildTimestamp: "${buildTime}",
  productName: "ABDAxionikVS",
  manufacturer: "ABDSynths",
} as const;
`;

fs.writeFileSync(buildTsPath, buildTsContent, 'utf8');

// 3. Ejecutar Vite build
console.log('[ABDAxionikVS] Ejecutando Vite build -> WebUI/dist/ ...');
const npxCmd = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const res = spawnSync(npxCmd, ['vite', 'build'], {
  cwd: rootDir,
  stdio: 'inherit',
  shell: true,
});

if (res.status !== 0) {
  console.error('[ABDAxionikVS] Error al compilar WebUI bundle.');
  process.exit(res.status || 1);
}

console.log('[ABDAxionikVS] WebUI bundle compilado con éxito en WebUI/dist/.');
